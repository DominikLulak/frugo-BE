-- ============================================================
-- 1. DROP OLD EVENT / MOVEMENT TABLES
-- ============================================================

-- Drop dependent tables first.
DROP TABLE IF EXISTS event_log_entity;
DROP TABLE IF EXISTS event_log_step;
DROP TABLE IF EXISTS event_log;
DROP TABLE IF EXISTS stock_movement;
DROP TABLE IF EXISTS event_definition;


-- ============================================================
-- 2. STOCK MOVEMENT DEFINITIONS
-- ============================================================

CREATE TABLE stock_movement_definition (
                                           id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           code VARCHAR(100) NOT NULL UNIQUE,
                                           name VARCHAR(150) NOT NULL UNIQUE,
                                           description VARCHAR NOT NULL
);


-- ============================================================
-- 3. STOCK MOVEMENT
-- ============================================================

CREATE TABLE stock_movement (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                stock_movement_definition_id INTEGER NOT NULL,
                                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                purchase_order_id INTEGER,

                                warehouse_item_id INTEGER NOT NULL,
                                new_warehouse_item_id INTEGER,

                                quantity INTEGER NOT NULL,

                                from_location_id INTEGER,
                                to_location_id INTEGER,

                                employee_id INTEGER NOT NULL,

                                pallet_id INTEGER,
                                order_id INTEGER,
                                shipment_id INTEGER,

                                CONSTRAINT chk_stock_movement_quantity
                                    CHECK (quantity > 0),

                                CONSTRAINT chk_stock_movement_different_items
                                    CHECK (
                                        new_warehouse_item_id IS NULL
                                            OR new_warehouse_item_id <> warehouse_item_id
                                        ),

                                CONSTRAINT fk_stock_movement_definition
                                    FOREIGN KEY (stock_movement_definition_id)
                                        REFERENCES stock_movement_definition(id),

                                CONSTRAINT fk_stock_movement_purchase_order
                                    FOREIGN KEY (purchase_order_id)
                                        REFERENCES purchase_order(id),

                                CONSTRAINT fk_stock_movement_warehouse_item
                                    FOREIGN KEY (warehouse_item_id)
                                        REFERENCES warehouse_item(id),

                                CONSTRAINT fk_stock_movement_new_warehouse_item
                                    FOREIGN KEY (new_warehouse_item_id)
                                        REFERENCES warehouse_item(id),

                                CONSTRAINT fk_stock_movement_from_location
                                    FOREIGN KEY (from_location_id)
                                        REFERENCES location(id),

                                CONSTRAINT fk_stock_movement_to_location
                                    FOREIGN KEY (to_location_id)
                                        REFERENCES location(id),

                                CONSTRAINT fk_stock_movement_employee
                                    FOREIGN KEY (employee_id)
                                        REFERENCES employee(id),

                                CONSTRAINT fk_stock_movement_pallet
                                    FOREIGN KEY (pallet_id)
                                        REFERENCES pallet(id),

                                CONSTRAINT fk_stock_movement_order
                                    FOREIGN KEY (order_id)
                                        REFERENCES orders(id),

                                CONSTRAINT fk_stock_movement_shipment
                                    FOREIGN KEY (shipment_id)
                                        REFERENCES shipment(id)
);


