-- ============================================================
-- 5. EVENT LOG DEFINITIONS
-- ============================================================

CREATE TABLE event_log_definition (
                                      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      code VARCHAR(100) NOT NULL UNIQUE,
                                      name VARCHAR(150) NOT NULL UNIQUE,
                                      description VARCHAR NOT NULL
);


-- ============================================================
-- 6. EVENT LOG
-- ============================================================

CREATE TABLE event_log (
                           id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           event_log_definition_id INTEGER NOT NULL,

                           started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           finished_at TIMESTAMP,

                           employee_id INTEGER,

                           status VARCHAR(30) NOT NULL,

                           reference VARCHAR(150),

                           description VARCHAR NOT NULL,

                           data JSONB,

                           CONSTRAINT chk_event_log_status
                               CHECK (
                                   status IN (
                                              'IN_PROGRESS',
                                              'SUCCESS',
                                              'PARTIAL_SUCCESS',
                                              'FAILED'
                                       )
                                   ),

                           CONSTRAINT chk_event_log_finished_at
                               CHECK (
                                   finished_at IS NULL
                                       OR finished_at >= started_at
                                   ),

                           CONSTRAINT fk_event_log_definition
                               FOREIGN KEY (event_log_definition_id)
                                   REFERENCES event_log_definition(id),

                           CONSTRAINT fk_event_log_employee
                               FOREIGN KEY (employee_id)
                                   REFERENCES employee(id)
);


-- ============================================================
-- 7. EVENT LOG STEP
-- ============================================================

CREATE TABLE event_log_step (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                event_log_id INTEGER NOT NULL,

                                step_number INTEGER NOT NULL,

                                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                finished_at TIMESTAMP,

                                name VARCHAR(150) NOT NULL,
                                description VARCHAR,

                                status VARCHAR(30) NOT NULL,

                                error_code VARCHAR(100),
                                error_message TEXT,

                                data JSONB,

                                CONSTRAINT chk_event_log_step_number
                                    CHECK (step_number > 0),

                                CONSTRAINT chk_event_log_step_status
                                    CHECK (
                                        status IN (
                                                   'IN_PROGRESS',
                                                   'SUCCESS',
                                                   'WARNING',
                                                   'FAILED',
                                                   'SKIPPED'
                                            )
                                        ),

                                CONSTRAINT chk_event_log_step_finished_at
                                    CHECK (
                                        finished_at IS NULL
                                            OR finished_at >= created_at
                                        ),

                                CONSTRAINT uq_event_log_step_number
                                    UNIQUE (event_log_id, step_number),

                                CONSTRAINT fk_event_log_step_event
                                    FOREIGN KEY (event_log_id)
                                        REFERENCES event_log(id)
);


-- ============================================================
-- 8. EVENT LOG ENTITY
-- ============================================================

CREATE TABLE event_log_entity (
                                  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  event_log_id INTEGER NOT NULL,

                                  entity_type VARCHAR(100) NOT NULL,
                                  entity_id INTEGER NOT NULL,

                                  CONSTRAINT uq_event_log_entity
                                      UNIQUE (event_log_id, entity_type, entity_id),

                                  CONSTRAINT fk_event_log_entity_event
                                      FOREIGN KEY (event_log_id)
                                          REFERENCES event_log(id)
);


