CREATE TABLE order_status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    old_status_id INTEGER NULL,
    new_status_id INTEGER NOT NULL,
    employee_id INTEGER NULL,
    note TEXT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_status_history_order
        FOREIGN KEY (order_id)
            REFERENCES orders(id),

    CONSTRAINT fk_order_status_history_old_status
        FOREIGN KEY (old_status_id)
            REFERENCES status(id),

    CONSTRAINT fk_order_status_history_new_status
        FOREIGN KEY (new_status_id)
            REFERENCES status(id),

    CONSTRAINT fk_order_status_history_employee
        FOREIGN KEY (employee_id)
            REFERENCES employee(id)
);

